function parseTable(text, zones) {
  const lines = text.trim().split(/\r?\n/);
  const rates = {};
  
  for (let z of zones) {
    rates[z] = {};
  }
  
  for (let line of lines) {
    const parts = line.split(/\s+/);
    if (parts.length > 1 && !isNaN(parseFloat(parts[0]))) {
      const weight = parts[0];
      for (let i = 0; i < zones.length; i++) {
        if (parts[i+1]) {
          rates[zones[i]][weight] = parseInt(parts[i+1].replace(/,/g, ''), 10);
        }
      }
    }
  }
  return rates;
}

